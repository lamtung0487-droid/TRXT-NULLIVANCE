# Combine all data
FULL_DATA = SPARC_DATA + "\n" + ADDITIONAL_GALAXIES.strip()

def main():
    # Parse the embedded data
    from sparc_data_loader import SPARCGalaxy
    import numpy as np
    
    lines = FULL_DATA.strip().split('\n')
    
    galaxies = {}
    for line in lines:
        parts = line.split()
        if len(parts) >= 7:
            name = parts[0]
            r = float(parts[2])
            vobs = float(parts[3])
            verr = float(parts[4])
            vgas = float(parts[5])
            vdisk = float(parts[6])
            vbul = float(parts[7]) if len(parts) > 7 else 0.0
            
            if name not in galaxies:
                galaxies[name] = {'r': [], 'vobs': [], 'verr': [], 'vgas': [], 'vdisk': [], 'vbul': []}
            
            galaxies[name]['r'].append(r)
            galaxies[name]['vobs'].append(vobs)
            galaxies[name]['verr'].append(verr)
            galaxies[name]['vgas'].append(vgas)
            galaxies[name]['vdisk'].append(vdisk)
            galaxies[name]['vbul'].append(vbul)
    
    # Convert to SPARCGalaxy objects
    result = {}
    for name, data in galaxies.items():
        if len(data['r']) >= 5:
            result[name] = SPARCGalaxy(
                name=name,
                r_kpc=np.array(data['r']),
                v_obs=np.array(data['vobs']),
                v_err=np.array(data['verr']),
                v_gas=np.array(data['vgas']),
                v_disk=np.array(data['vdisk']),
                v_bul=np.array(data['vbul']),
                distance_mpc=0.0,
                inclination=0.0,
                luminosity=0.0,
                morphology="Spiral"
            )
    
    print(f"Loaded {len(result)} galaxies from embedded data")
    return result

if __name__ == "__main__":
    galaxies = main()
    for name, g in galaxies.items():
        print(f"  {name}: {len(g.r_kpc)} points, v_max={max(g.v_obs):.1f} km/s")
